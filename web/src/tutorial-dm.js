// tutorial-dm.js — шаги режима обучения на экране ДМ (см. tutorial.js —
// сам движок). Порядок — тот, в котором стол готовят к первой игре: сцена и
// карта → библиотека (модули Foundry, TTG Club) → персонажи (LSS) → токены →
// инициатива → доски и журнал. Рассчитано на 10–15 минут вместе с тем, что
// человек делает руками по ходу.
//
// Цели — селекторы по dm.html, а панели открываются кликом по тем же
// кнопкам, что жмёт человек: у dm.js нет и не нужно API «открой раздел»
// для тура, а клик по рейлу делает всё, что делает клик по рейлу.

// openRailSection — раздел рейла (левая панель): клик по кнопке, только
// если раздел ещё не открыт — иначе клик его закроет.
function openRailSection(btnId) {
  const btn = document.getElementById(btnId);
  if (btn && !btn.classList.contains("active")) btn.click();
}

// closeRailSection — убрать левую панель, когда шаг про правую колонку или
// про карту: открытая с прошлого шага, она только отвлекает.
function closeRailSection() {
  document.querySelector("#panel .panel-section.active .panel-close")?.click();
}

// openSideMenu — панель правой колонки (справочник, доски): кнопки без id,
// ищем по подписи.
function sideMenuBtn(title) {
  return document.querySelector(`.vtt-side-menu-btn[aria-label="${title}"]`);
}
function sideMenuPanel(title) {
  return sideMenuBtn(title)?.parentElement?.querySelector(".vtt-side-panel") || null;
}
function openSideMenu(title) {
  const btn = sideMenuBtn(title);
  if (btn && !btn.classList.contains("open")) btn.click();
}

// compendiumNode — пункт дерева справочника по подписи (см.
// compendium-menu.js: leafNode).
function compendiumNode(label) {
  return [...document.querySelectorAll(".compendium-node")].find((b) => b.textContent.includes(label)) || null;
}

// openSettingsTab — «Настройки» живут в меню «⋯» рейла; кнопка спрятана,
// но click() у неё работает и меню закрывает сам dm.js.
function openSettingsTab(tab) {
  openRailSection("settingsBtn");
  document.querySelector(`.set-tabs [data-settab="${tab}"]`)?.click();
}

