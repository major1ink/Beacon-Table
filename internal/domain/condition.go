package domain

import "time"

// Condition — карточка справочника состояний (ослепление, испуг, истощение,
// «концентрация», самодельная метка ДМ «горит» и т.п.), общая на весь стол.
// Хранится файлом на диске, один JSON на состояние (см.
// internal/repository/conditionfile) — та же идея, что у Monster/Spell/Item/
// Reference, с тем же делением на каталог «из коробки» (System) и
// пользовательскую библиотеку.
//
// ЭТО СПРАВОЧНИК, А НЕ НАЛОЖЕННЫЙ СТАТУС. То, что реально висит на токене/
// бойце в бою — AppliedStatus (см. scene.go): снимок нескольких полей
// отсюда плюс длительность/уровень/источник. Такое разделение — прямой
// аналог Foundry (CONFIG.statusEffects — словарь, ActiveEffect — то, что
// висит на актёре), и оно же спасает от битых ссылок: удаление карточки не
// снимает уже наложенные метки и не оставляет их без имени.
//
// ЧТО СОСТОЯНИЕ УМЕЕТ МЕНЯТЬ. Всё числовое — через Modifiers (см.
// domain.Modifier): «−2 к КД», «скорость 0», «1к6 огнём в начале хода».
// Приложение реально применяет их — к эффективным числам бойца в трекере, к
// хитам по ходам и к листу персонажа. Всё нечисловое (преимущество/помеха,
// автопровал спасброска, «не может говорить») остаётся текстом в Mechanics
// и Description: это не арифметика, а формулировки правил, и разбирать их
// приложение не должно — так же, как оно не разбирает текст способностей
// монстра (см. комментарий про roller в monster.go).
//
// Граница с Foundry проходит здесь же. У ActiveEffect.changes ключом может
// быть любое поле модели актёра, потому что модель принадлежит системе
// правил; у нас цели — закрытый список ModifierTargets, ровно те числа,
// которые приложение показывает. Импорт из Foundry раскладывает changes[] по
// этому списку, а всё, что в него не попало, оставляет расшифровкой в
// Mechanics (см. web/src/condition-import.js).
type Condition struct {
	ID   string `json:"id"`
	Name string `json:"name"`
	// System — true для карточек каталога «из коробки», зашитого в бинарник
	// на этапе компиляции (см. internal/repository/conditionfile.SystemStore) —
	// проставляется сервером при чтении, клиентское значение в Create/Update
	// игнорируется (см. conditionfile.Catalog). Такие карточки нельзя
	// редактировать/удалять — только клонировать в библиотеку и править копию
	// (кнопка «Клонировать», см. web/src/pages/conditions.js).
	System bool   `json:"system,omitempty"`
	Source string `json:"source,omitempty"` // "PHB'24", "самодельное"...

	// Slug — стабильный машинный ключ состояния ("blinded", "prone",
	// "concentrating"), НЕ ID. Три роли, ради которых он вообще заведён:
	//
	//  1. Мост к Foundry: в экспорте Foundry статус приходит именно кодом
	//     (ActiveEffect.statuses: ["prone"]), см. web/src/foundry-conditions.js —
	//     по slug импортированный эффект находит нашу карточку и получает
	//     русское имя/иконку вместо сырого кода.
	//  2. Ключ ссылки у наложенной метки (AppliedStatus.Slug) и у заклинания
	//     (SpellStatusRef.Slug) — переживает и клонирование карточки, и
	//     пересборку каталога «из коробки» (ID системных карточек зависит от
	//     имени файла, а slug — нет).
	//  3. Ключ зависимых состояний (Riders ниже).
	//
	// Уникальность slug'а НЕ обеспечивается сервером (это тот же «умный
	// бланк»): при двух карточках с одним slug побеждает та, что раньше в
	// алфавитном списке — см. service.ConditionService.BySlug.
	Slug string `json:"slug,omitempty"`

	// Icon — ОДИН символ-глиф (эмодзи), которым состояние рисуется значком
	// на токене и чипом в трекере. Именно эмодзи, а не имя иконки из
	// web/src/icons.js: значок нужен одновременно в HTML (палитра, чипы) и в
	// WebGL-сцене, а в Pixi эмодзи ставится обычным PIXI.Text — тем же
	// приёмом, которым уже нарисованы лампочка источника света и череп
	// мёртвого токена (см. web/src/vtt/layers/tokens.js). SVG из icons.js
	// пришлось бы растеризовать через data-URI отдельным путём ради того же
	// результата.
	Icon string `json:"icon,omitempty"`
	// ImageURL — необязательный собственный арт вместо глифа (загружается в
	// ту же категорию /uploads/tokens, что аватары и токен-арт монстров).
	// Если задан — рисуется вместо Icon и на токене, и в палитре.
	ImageURL string `json:"imageUrl,omitempty"`
	// Color — цвет каймы значка на токене и чипа в трекере ("#c0392b").
	// Пусто — клиент подставляет свой нейтральный дефолт.
	Color string `json:"color,omitempty"`

	// Overlay — рисовать значок во весь токен, а не маленьким кружком по
	// верхней кромке (аналог flags.core.overlay в Foundry). Для состояний,
	// которые важнее самого арта: «окаменение», «беспамятство».
	Overlay bool `json:"overlay,omitempty"`

	// Levels — 0 (или 1) для обычного тумблера «висит/не висит», >1 для
	// многоуровневых состояний: истощение — 6. У наложенной метки тогда
	// осмысленно AppliedStatus.Level (см. scene.go).
	Levels int `json:"levels,omitempty"`

	// Riders — slug'и состояний, включающихся ВМЕСТЕ с этим (в Foundry это
	// CONFIG.DND5E.conditionTypes[...].riders): "unconscious" тянет за собой
	// "incapacitated" и "prone", "paralyzed" — "incapacitated". Разворачивает
	// их сервер при наложении (см. service.Room.handleApplyStatus), причём на
	// ОДИН уровень вглубь: цепочки rider'ов у rider'ов не раскручиваем, чтобы
	// кольцевая ссылка в самодельной карточке не увела в бесконечность.
	// Снятие родителя зависимые НЕ снимает — они могли прилететь и сами по
	// себе, а угадывать за ДМ мы не беремся (Foundry ведёт себя так же).
	Riders []string `json:"riders,omitempty"`

	// DefaultRounds — сколько раундов состояние висит по умолчанию, 0 —
	// бессрочно (пока ДМ не снимет). Это только предзаполнение поля при
	// наложении, не правило: ДМ правит длительность у конкретной метки.
	DefaultRounds int `json:"defaultRounds,omitempty"`

	Description string `json:"description,omitempty"` // markdown/HTML — рендерится тем же marked, что и остальные карточки
	// Modifiers — что состояние РЕАЛЬНО меняет в числах: «−2 к КД»,
	// «скорость 0», «1к6 огнём в начале хода» (см. domain.Modifier).
	// Применяются приложением: постоянные — к эффективным числам бойца в
	// трекере и на листе персонажа, периодические — к текущим хитам в
	// начале/конце хода (см. service.Room.applyPeriodicModifiers).
	//
	// Это НЕ движок правил: приложение не выводит модификаторы из описания
	// состояния и не знает, что «ослепление» даёт помеху — оно применяет
	// ровно тот список, который завёл человек в конструкторе или принёс
	// импорт из Foundry (changes[] эффекта, см. web/src/condition-import.js).
	Modifiers []Modifier `json:"modifiers,omitempty"`
	// Mechanics — человекочитаемая выжимка того, что В ЧИСЛА НЕ ЛОЖИТСЯ:
	// «помеха на броски атаки», «атаки по существу с преимуществом»,
	// «автопровал спасбросков Силы». Преимущество/помеха, автопровалы и
	// прочее «не арифметическое» так и остаётся текстом для глаз ДМ — как и
	// формулировки в статблоке монстра.
	Mechanics string   `json:"mechanics,omitempty"`
	Tags      []string `json:"tags,omitempty"`

	UpdatedAt time.Time `json:"updatedAt"`
}

// NewCondition создаёт пустую карточку состояния с разумными дефолтами —
// как NewReference/NewItem/NewMonster/NewSpell, готова сразу отдаваться на
// редактирование (или на импорт поверх себя, см.
// web/src/condition-import.js).
func NewCondition(id, name string) *Condition {
	return &Condition{ID: id, Name: name, Icon: "❔"}
}
