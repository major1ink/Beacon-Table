package domain

import "time"

// Board — доска: бесконечный холст рядом с заметками, на котором за столом
// рисуют вместе (схема расследования, связи между NPC, наброски карты мира).
// В отличие от слоя пометок на сцене (см. Drawing), доска не привязана ни к
// какой карте и живёт своей жизнью.
//
// Модель владения и прав — та же, что у записи журнала (см. Sharing): у доски
// есть автор, уровень «по умолчанию» и точечные выдачи аккаунтам. Отсюда
// сразу два требуемых сценария, без отдельных сущностей: доска с
// Default >= JournalObserver — общая на стол, доска с Default = JournalNone —
// личная, и досок может быть сколько угодно одновременно.
//
// Содержимого холста здесь пока нет намеренно: формат хранения элементов
// решается вместе с совместимостью с плагином Excalidraw для Obsidian, и до
// этого решения заводить своё поле значило бы записать формат, который
// придётся выбрасывать.
type Board struct {
	ID string `json:"id"`
	// Name — имя доски. Отдельное поле, а не первая строка содержимого (как
	// Title у JournalEntry): у холста нет «первой строки», а переименование
	// должно быть отдельной операцией, а не правкой рисунка.
	Name string `json:"name"`
	Sharing
	UpdatedAt time.Time `json:"updatedAt"`
}
