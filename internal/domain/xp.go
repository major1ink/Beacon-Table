package domain

import "strings"

// crXPTable — стандартная таблица опыта за победу над существом данного
// уровня опасности (Dungeon Master's Guide, "Beating Encounters"). Ключи —
// в точности то, что попадает в Monster.CR ("1/2", "5"...). Используется
// ровно в одном месте — service.Room.killMonsterCombatant — чтобы в момент
// смерти монстра снять число опыта и положить его в Token.XP (см. scene.go),
// откуда его и читает вкладка "Убитые" трекера инициативы.
var crXPTable = map[string]int{
	"0": 10, "1/8": 25, "1/4": 50, "1/2": 100,
	"1": 200, "2": 450, "3": 700, "4": 1100, "5": 1800,
	"6": 2300, "7": 2900, "8": 3900, "9": 5000, "10": 5900,
	"11": 7200, "12": 8400, "13": 10000, "14": 11500, "15": 13000,
	"16": 15000, "17": 18000, "18": 20000, "19": 22000, "20": 25000,
	"21": 33000, "22": 41000, "23": 50000, "24": 62000, "25": 75000,
	"26": 90000, "27": 105000, "28": 120000, "29": 135000, "30": 155000,
}

// CRToXP переводит текстовый уровень опасности карточки монстра (Monster.CR)
// в опыт за победу над ним по таблице выше. Неизвестное или пустое значение
// (голый NPC-токен без статблока, нестандартная запись CR) даёт 0, а не
// ошибку — трекер просто не предложит опыт за такого бойца, ДМ при желании
// начислит его сам.
func CRToXP(cr string) int {
	return crXPTable[strings.TrimSpace(cr)]
}
